// Turns the requests that worked in Try it into one small typed HttpClient class: a method per distinct request,
// query values as parameters (defaulting to what was tested), response classes inferred from the saved responses.
// The saved key is never written out - {key} becomes a constructor parameter.
//
// A port of the desktop app's ClientGenerator. The two must write the same text for the same history:
// test/fixtures/codegen holds what the desktop writes, and the tests compare to the letter. Change both or neither.

import 'json_to_csharp.dart';
import 'tester.dart' show guessContentType, methodHasBody;
import 'user_data.dart' show TestHistoryEntry;
import 'variables.dart';

const _keyToken = 'APISCOUTKEYTOKEN';
const _keyCall = '{Uri.EscapeDataString(_apiKey)}';

final _skipSegmentRx = RegExp(r'^(api|apis|json|xml|rest|public|service|services|v\d+(\.\d+)*|\d+(\.\d+)+)$', caseSensitive: false);
final _keyNameRx = RegExp(r'^(api[-_]?key|apikey|key|token|access[-_]?token|access[-_]?key|app[-_]?id|appid|auth|client[-_]?id)$', caseSensitive: false);
final _decimalRx = RegExp(r'^-?\d+\.\d+$');
final _varSegmentRx = RegExp(r'^APISCOUTVAR(\d+)X$');
final _pathVariableRx = RegExp(r'(?<=/)\{([A-Za-z_][A-Za-z0-9_-]{0,39})\}(?=/|$)');
final _keyPlaceholderRx = RegExp(r'\{key\}', caseSensitive: false);
final _digitsRx = RegExp(r'^[0-9]+$');
final _signedDigitsRx = RegExp(r'^[+-]?[0-9]+$');
final _letterRx = RegExp(r'\p{L}', unicode: true);
final _letterFirstRx = RegExp(r'^[\p{L}_]', unicode: true);
final _numberSegmentRx = RegExp(r'/\d+(?=/|$)');
final _spaceRx = RegExp(r'\s+');

const _reservedNames = {'ct', 'url', 'request', 'response', 'body', 'http', 'apiKey'};
const _plainTypes = {'int', 'long', 'double', 'bool', 'string', 'object', 'JsonElement', 'DateTimeOffset'};
const _int32Max = 2147483647, _int32Min = -2147483648;

class _Param {
  final String type, name, def;
  const _Param(this.type, this.name, this.def);
}

/// One client class, before the file around it is written.
class _Part {
  final String className, code, firstCall;
  final int methods;
  final bool usesKey, usesDemoKey, usesCulture, usesText;
  final String? demoKey;
  const _Part(this.className, this.code, this.methods, this.firstCall, this.usesKey, this.usesDemoKey, this.demoKey, this.usesCulture, this.usesText);
}

/// One API's share of a collection client.
class ClientSource {
  final String apiName;
  final Iterable<TestHistoryEntry> history;
  final String? demoKey;
  final Map<String, String>? variables;
  const ClientSource(this.apiName, this.history, {this.demoKey, this.variables});
}

/// Null when no successful request is in the history yet.
/// [variables] are the API's request variables: {city} in a tested URL becomes a parameter that defaults to its value.
String? generateClient(String apiName, Iterable<TestHistoryEntry> history, {String? demoKey, Map<String, String>? variables}) {
  final classes = CsClassSet();
  final part = _build(clientClassName(apiName), history, demoKey, classes, variables);
  if (part == null) return null;

  final code = StringBuffer()
    ..writeln('// ${part.className} - generated by API Free from ${part.methods} request${part.methods == 1 ? '' : 's'} that worked in "Try it".')
    ..writeln('// Types come from one response each: widen int to double, or add ?, where the API can answer differently.')
    ..writeln('//')
    ..writeln('//   var client = new ${part.className}(new HttpClient()${part.usesKey && !part.usesDemoKey ? ', "your key"' : ''});')
    ..writeln('//   var result = await client.${part.firstCall};')
    ..writeln();
  _usings(code, [part]);
  code.writeln(part.code);
  if (!classes.isEmpty) code.write(classes.render());
  return code.toString().trimRight();
}

/// One file for a whole collection: a client class per API (those with a successful test), response classes named
/// uniquely across all of them, and a small facade that builds every client from one HttpClient.
/// Null when none of the APIs has a successful test yet.
String? generateCollectionClient(String collectionName, Iterable<ClientSource> apis) {
  final classes = CsClassSet();
  final facade = '${_trimStart(csPascal(collectionName), '@')}Apis';
  classes.reserve(facade);
  final parts = <_Part>[];
  final names = {facade};
  for (final api in apis) {
    var name = clientClassName(api.apiName);
    for (var n = 2; names.contains(name); n++) {
      name = '${clientClassName(api.apiName)}$n'; // two APIs called "Dogs"
    }
    final part = _build(name, newestOfEachRequest(api.history), api.demoKey, classes, api.variables);
    if (part != null) {
      names.add(name);
      parts.add(part);
    }
  }
  if (parts.isEmpty) return null;

  // "DogsClient2" -> "Dogs2"
  String prop(_Part p) {
    final at = p.className.lastIndexOf('Client');
    return at > 0 ? p.className.replaceRange(at, at + 6, '') : p.className;
  }

  String keyArg(_Part p) => '${_lowerFirst(prop(p))}Key';

  final requests = parts.fold(0, (sum, p) => sum + p.methods);
  final code = StringBuffer()
    ..writeln('// $facade - generated by API Free from the collection "${collectionName.replaceAll('\n', ' ')}": ${parts.length} API${parts.length == 1 ? '' : 's'}, $requests requests that worked in "Try it".')
    ..writeln('// Types come from one response each: widen int to double, or add ?, where the API can answer differently.')
    ..writeln('//')
    ..writeln('//   var apis = new $facade(new HttpClient()${[for (final p in parts) if (p.usesKey && !p.usesDemoKey) ', ${keyArg(p)}: "your key"'].join()});')
    ..writeln('//   var result = await apis.${prop(parts[0])}.${parts[0].firstCall};')
    ..writeln();
  _usings(code, parts);

  // required keys first, then the ones that default to a provider's demo key
  final args = [
    for (final p in parts) if (p.usesKey && !p.usesDemoKey) ', string ${keyArg(p)}',
    for (final p in parts) if (p.usesKey && p.usesDemoKey) ', string ${keyArg(p)} = ${_quote(p.demoKey!)}',
  ];
  code
    ..writeln('/// <summary>Every client of the collection on one HttpClient.</summary>')
    ..writeln('public sealed class $facade')
    ..writeln('{')
    ..writeln('    public $facade(HttpClient http${args.join()})')
    ..writeln('    {');
  for (final p in parts) {
    code.writeln('        ${prop(p)} = new ${p.className}(http${p.usesKey ? ', ${keyArg(p)}' : ''});');
  }
  code
    ..writeln('    }')
    ..writeln();
  for (final p in parts) {
    code.writeln('    public ${p.className} ${prop(p)} { get; }');
  }
  code.writeln('}');
  for (final p in parts) {
    code
      ..writeln()
      ..writeln(p.code);
  }
  if (!classes.isEmpty) code.write(classes.render());
  return code.toString().trimRight();
}

void _usings(StringBuffer code, List<_Part> parts) {
  code
    ..writeln('using System;')
    ..writeln('using System.Collections.Generic;');
  if (parts.any((p) => p.usesCulture)) code.writeln('using System.Globalization;');
  code
    ..writeln('using System.Net.Http;')
    ..writeln('using System.Net.Http.Json;');
  if (parts.any((p) => p.usesText)) code.writeln('using System.Text;');
  code
    ..writeln('using System.Text.Json;')
    ..writeln('using System.Text.Json.Serialization;')
    ..writeln('using System.Threading;')
    ..writeln('using System.Threading.Tasks;')
    ..writeln();
}

/// Newest first; tests made in the same instant keep the order they came in (as LINQ's OrderByDescending does).
List<TestHistoryEntry> _newestFirst(Iterable<TestHistoryEntry> history) {
  final indexed = history.indexed.toList()
    ..sort((a, b) {
      final byTime = b.$2.at.compareTo(a.$2.at);
      return byTime != 0 ? byTime : a.$1.compareTo(b.$1);
    });
  return [for (final (_, h) in indexed) h];
}

_Part? _build(String className, Iterable<TestHistoryEntry> history, String? demoKey, CsClassSet classes, Map<String, String>? variables) {
  classes.reserve(className);

  final methods = <String>[];
  final methodNames = <String>{};
  final shapes = <String?>{};
  var usesKey = false, usesDemoKey = false, usesCulture = false, usesText = false;
  String? firstCall;

  for (final h in _newestFirst(history.where((h) => h.ok))) {
    // the key never appears in the code: {key} and the provider's demo key both become _apiKey
    var demoHere = false;
    String mark(String s) {
      s = s.replaceAll(_keyPlaceholderRx, _keyToken);
      if (demoKey != null && demoKey.length >= 4 && s.contains(demoKey)) {
        s = s.replaceAll(demoKey, _keyToken);
        demoHere = true;
      }
      return s;
    }

    // request variables: a whole path segment ({city}) becomes a parameter of its own; anywhere else the value is
    // filled in, where a query value turns into a parameter with that default anyway
    final pathVars = <(String, String)>[];
    var rawUrl = h.url.trim();
    final queryAt = rawUrl.indexOf('?');
    final rawPath = (queryAt < 0 ? rawUrl : rawUrl.substring(0, queryAt)).replaceAllMapped(_pathVariableRx, (m) {
      final value = variableValue(m.group(1)!, variables, h.at);
      if (value == null) return m.group(0)!;
      pathVars.add((m.group(1)!, value));
      return 'APISCOUTVAR${pathVars.length - 1}X';
    });
    rawUrl = fillVariables(rawPath + (queryAt < 0 ? '' : rawUrl.substring(queryAt)), variables, escape: true, now: h.at);
    var urlText = mark(rawUrl);
    if (demoKey != null && demoKey.isNotEmpty && demoKey.length < 4) {
      final (marked, found) = _markShortKey(urlText, demoKey);
      urlText = marked;
      if (found) demoHere = true;
    }
    final uri = _absolute(urlText);
    if (uri == null) continue;
    final method = h.method.trim().toUpperCase();

    // ---- path: numeric segments after a word become id parameters
    final parameters = <_Param>[];
    final used = {..._reservedNames};
    final path = StringBuffer();
    final words = <String>[];
    var endsWithId = false;
    String? previousWord;
    for (final raw in uri.path.split('/')) {
      if (raw.isEmpty) continue;
      path.write('/');
      endsWithId = false;
      if (raw.contains(_keyToken)) {
        path.write(_lit(raw).replaceAll(_keyToken, _keyCall));
        previousWord = null;
        continue;
      }
      final seg = _varSegmentRx.firstMatch(raw);
      if (seg != null) {
        final (varName, varValue) = pathVars[int.parse(seg.group(1)!)];
        final name = _unique(_lowerFirstOr(_trimStart(csPascal(varName), '@_')), used);
        final number = _digitsRx.hasMatch(varValue) && _fitsInt32(varValue);
        parameters.add(_Param(number ? 'int' : 'string', name, number ? varValue : _quote(varValue)));
        path.write(number ? '{$name}' : '{Uri.EscapeDataString($name)}');
        endsWithId = true;
        previousWord = null;
        continue;
      }
      if (previousWord != null && _digitsRx.hasMatch(raw) && raw.length <= 18) {
        final name = _unique('${_lowerFirstOr(_trimStart(csPascal(_single(previousWord)), '@_'))}Id', used);
        parameters.add(_Param(int.parse(raw) <= _int32Max ? 'int' : 'long', name, raw));
        path.write('{$name}');
        endsWithId = true;
        previousWord = null;
        continue;
      }
      path.write(_lit(raw));
      final word = _fileNameWithoutExtension(_unescape(raw, plusIsSpace: false));
      if (word.isNotEmpty && !_skipSegmentRx.hasMatch(word) && _letterRx.hasMatch(word)) {
        words.add(word);
        previousWord = word;
      } else {
        previousWord = null;
      }
    }

    // ---- query: every value becomes a parameter that defaults to what was tested
    final query = StringBuffer();
    for (final pair in uri.query.split('&')) {
      if (pair.isEmpty) continue;
      final eq = pair.indexOf('=');
      final rawName = eq < 0 ? pair : pair.substring(0, eq);
      final value = eq < 0 ? '' : _unescape(pair.substring(eq + 1));
      query
        ..write(query.isEmpty ? '?' : '&')
        ..write(_lit(rawName));
      if (eq < 0) continue;
      query.write('=');
      if (value.contains(_keyToken)) {
        query.write(value == _keyToken ? _keyCall : _lit(value).replaceAll(_keyToken, _keyCall));
        continue;
      }

      final pname = _unique(_lowerFirstOr(_trimStart(csPascal(_unescape(rawName)), '@_')), used);
      if (_signedDigitsRx.hasMatch(value) && _fitsInt32(value) && (value == '0' || !_trimStart(value, '-').startsWith('0'))) {
        parameters.add(_Param('int', pname, value));
        query.write('{$pname}');
      } else if (_decimalRx.hasMatch(value)) {
        parameters.add(_Param('double', pname, value));
        query.write('{$pname.ToString(CultureInfo.InvariantCulture)}');
        usesCulture = true;
      } else {
        parameters.add(_Param('string', pname, _quote(value)));
        query.write('{Uri.EscapeDataString($pname)}');
      }
    }

    // one method per distinct request shape - the newest test of it wins
    if (!shapes.add(requestShapeOf(h))) continue;

    // ---- name
    final noun = words.isEmpty ? 'Data' : _trimStart(csPascal(endsWithId ? _single(words.last) : words.last), '@_');
    final baseName = '${_verb(method)}$noun';
    var methodName = baseName;
    for (var n = 2; !methodNames.add(methodName); n++) {
      methodName = '$baseName$n';
    }

    // ---- headers
    final headerLines = <String>[];
    final headers = _headerPairs(mark(fillVariables(h.headers, variables, now: h.at)));
    String? contentType;
    for (final (name, value) in headers) {
      if (name.toLowerCase() == 'content-type') {
        contentType = value;
        continue;
      }
      final text = value == _keyToken
          ? '_apiKey'
          : value.contains(_keyToken)
              ? '\$"${_lit(value).replaceAll(_keyToken, '{_apiKey}')}"'
              : _quote(value);
      headerLines.add('request.Headers.TryAddWithoutValidation(${_quote(name)}, $text);');
    }

    // ---- body
    String? contentLine;
    final body = fillVariables(h.body, variables, now: h.at).trim();
    if (methodHasBody(method) && body.isNotEmpty) {
      final markedBody = mark(body);
      final bodyType = markedBody.contains(_keyToken) ? null : classes.add(body, '${methodName}Request');
      if (bodyType != null && _isModel(bodyType)) {
        parameters.insert(0, _Param(_trimEnd(bodyType, '?'), 'body', ''));
        contentLine = 'request.Content = JsonContent.Create(body);';
      } else {
        parameters.insert(0, const _Param('string', 'body', ''));
        final type = (contentType ?? guessContentType(body)).split(';')[0].trim();
        contentLine = 'request.Content = new StringContent(body${markedBody.contains(_keyToken) ? '.Replace("{key}", _apiKey)' : ''}, Encoding.UTF8, ${_quote(type)});';
        usesText = true;
      }
    }

    // ---- response
    final sample = h.response.trim();
    String responseType = '';
    if (sample.isNotEmpty) {
      final t = classes.add(sample, '${methodName}Response');
      responseType = t == null
          ? 'string'
          : _isModel(t)
              ? _trimEnd(t, '?')
              : 'JsonElement';
    }

    if (urlText.contains(_keyToken) || headers.any((x) => x.$2.contains(_keyToken)) || mark(body).contains(_keyToken)) usesKey = true;
    if (demoHere) usesDemoKey = true;

    // ---- the method
    final sb = StringBuffer()..writeln('    /// <summary>$method ${_xml(h.url.trim())}</summary>');
    if (contentLine != null && body.length <= 400) {
      sb.writeln('    /// <remarks>Tested with this body: ${_xml(body.replaceAll(_spaceRx, ' '))}</remarks>');
    }
    final args = [
      for (final p in parameters) if (p.def.isEmpty) '${p.type} ${p.name}',
      for (final p in parameters) if (p.def.isNotEmpty) '${p.type} ${p.name} = ${p.def}',
      'CancellationToken ct = default',
    ].join(', ');
    final returns = switch (responseType) {
      '' => 'Task',
      'string' => 'Task<string>',
      'JsonElement' => 'Task<JsonElement>',
      _ => 'Task<$responseType?>',
    };
    sb
      ..writeln('    public async $returns ${methodName}Async($args)')
      ..writeln('    {')
      ..writeln('        var url = \$"${_lit('${uri.scheme}://${uri.authority}')}$path$query";')
      ..writeln('        using var request = new HttpRequestMessage(HttpMethod.${_verb(method)}, url);');
    for (final line in headerLines) {
      sb.writeln('        $line');
    }
    if (contentLine != null) sb.writeln('        $contentLine');
    sb
      ..writeln('        using var response = await _http.SendAsync(request, ct);')
      ..writeln('        response.EnsureSuccessStatusCode();');
    if (responseType == 'string') {
      sb.writeln('        return await response.Content.ReadAsStringAsync(ct); // the tested response was not (complete) JSON');
    } else if (responseType.isNotEmpty) {
      sb.writeln('        return await response.Content.ReadFromJsonAsync<$responseType>(ct);');
    }
    sb.write('    }');
    methods.add(sb.toString());
    firstCall ??= '${methodName}Async(${parameters.any((p) => p.def.isEmpty) ? '…' : ''})';
  }

  if (methods.isEmpty) return null;

  final code = StringBuffer()
    ..writeln('public sealed class $className')
    ..writeln('{')
    ..writeln('    private readonly HttpClient _http;');
  if (usesKey) code.writeln('    private readonly string _apiKey;');
  code.writeln();
  if (usesKey && usesDemoKey) {
    code.writeln('    /// <param name="apiKey">Defaults to the provider\'s shared demo key, which is heavily rate limited - pass your own.</param>');
  }
  code
    ..writeln('    public $className(HttpClient http${usesKey ? ', string apiKey${usesDemoKey ? ' = ${_quote(demoKey!)}' : ''}' : ''})')
    ..writeln('    {')
    ..writeln('        _http = http;');
  if (usesKey) code.writeln('        _apiKey = apiKey;');
  code.writeln('    }');
  for (final m in methods) {
    code
      ..writeln()
      ..writeln(m);
  }
  code.write('}');
  return _Part(className, code.toString(), methods.length, firstCall!, usesKey, usesDemoKey, demoKey, usesCulture, usesText);
}

/// What makes two tests "the same request": method, host, path (ids ignored) and parameter names. Null for an unusable URL.
String? requestShapeOf(TestHistoryEntry h) {
  final uri = _absolute(h.url.trim().replaceAll(_keyPlaceholderRx, 'KEY'));
  if (uri == null) return null;
  final names = [for (final p in uri.query.split('&')) if (p.isNotEmpty) p.split('=')[0]]..sort();
  return '${h.method.trim().toUpperCase()} ${uri.host}${uri.path.replaceAll(_numberSegmentRx, '/#')}?${names.join('&')}';
}

/// The tests that worked, newest first - what the client can be built from.
List<TestHistoryEntry> usableRequests(Iterable<TestHistoryEntry> history) => _newestFirst(history.where((h) => h.ok && requestShapeOf(h) != null));

/// The newest test of each distinct request - the default selection.
List<TestHistoryEntry> newestOfEachRequest(Iterable<TestHistoryEntry> history) {
  final seen = <String>{};
  return [for (final h in usableRequests(history)) if (seen.add(requestShapeOf(h)!)) h];
}

/// "ReqResClient" - also the suggested file name.
String clientClassName(String apiName) => '${_trimStart(csPascal(apiName), '@')}Client';

/// An absolute URL with a host, as .NET's Uri.TryCreate(…, Absolute) accepts for the URLs Try it can send.
Uri? _absolute(String text) {
  final uri = Uri.tryParse(text);
  return uri == null || !uri.hasScheme || uri.host.isEmpty ? null : uri;
}

/// A demo key as short as "1" is only trusted where the name says it is a key (?api_key=1).
(String, bool) _markShortKey(String url, String demoKey) {
  final q = url.indexOf('?');
  if (q < 0) return (url, false);
  var found = false;
  final pairs = url.substring(q + 1).split('&');
  for (var i = 0; i < pairs.length; i++) {
    final eq = pairs[i].indexOf('=');
    if (eq > 0 && pairs[i].substring(eq + 1) == demoKey && _keyNameRx.hasMatch(pairs[i].substring(0, eq))) {
      pairs[i] = '${pairs[i].substring(0, eq + 1)}$_keyToken';
      found = true;
    }
  }
  return ('${url.substring(0, q + 1)}${pairs.join('&')}', found);
}

/// "Name: value" lines up to the first one that is not (the desktop's ParseHeaders, whose result is used either way).
List<(String, String)> _headerPairs(String text) {
  final list = <(String, String)>[];
  for (final raw in text.split('\n')) {
    final line = raw.trim();
    if (line.isEmpty) continue;
    final colon = line.indexOf(':');
    if (colon <= 0) break;
    final name = line.substring(0, colon).trim(), value = line.substring(colon + 1).trim();
    if (name.isEmpty || value.isEmpty) break;
    list.add((name, value));
  }
  return list;
}

bool _isModel(String type) => type.startsWith('List<') || !_plainTypes.contains(_trimEnd(type, '?'));

String _verb(String method) => switch (method) { 'POST' => 'Post', 'PUT' => 'Put', 'PATCH' => 'Patch', 'DELETE' => 'Delete', _ => 'Get' };

String _single(String word) {
  final s = csSingular(word);
  return s == '${word}Item' ? word : s;
}

String _lowerFirst(String s) {
  if (s.isEmpty) return s;
  final first = s.substring(0, 1), low = first.toLowerCase();
  return (low.length == 1 ? low : first) + s.substring(1);
}

/// Camel case for a parameter; "value" when nothing is left of the name.
String _lowerFirstOr(String pascal) => pascal.isEmpty ? 'value' : _lowerFirst(pascal);

String _unique(String name, Set<String> used) {
  if (name.isEmpty || !_letterFirstRx.hasMatch(name)) name = 'p$name';
  if (csIsKeyword(name)) name += 'Value'; // "in", "long"…
  var candidate = name;
  for (var n = 2; !used.add(candidate); n++) {
    candidate = '$name$n';
  }
  return candidate;
}

bool _fitsInt32(String digits) {
  final v = BigInt.parse(digits.startsWith('+') ? digits.substring(1) : digits);
  return v >= BigInt.from(_int32Min) && v <= BigInt.from(_int32Max);
}

/// Percent-decoding that gives the text back as it was when it is not valid ([plusIsSpace] for a query value).
String _unescape(String s, {bool plusIsSpace = true}) {
  try {
    return Uri.decodeComponent(plusIsSpace ? s.replaceAll('+', ' ') : s);
  } on ArgumentError {
    return s;
  } on FormatException {
    return s;
  }
}

/// "search.php" → "search", as Path.GetFileNameWithoutExtension has it.
String _fileNameWithoutExtension(String s) {
  final slash = s.lastIndexOf(RegExp(r'[/\\]'));
  var name = slash < 0 ? s : s.substring(slash + 1);
  if (slash < 0 && name.length >= 2 && name[1] == ':' && RegExp(r'^[A-Za-z]').hasMatch(name)) name = name.substring(2); // "c:file"
  final dot = name.lastIndexOf('.');
  return dot < 0 ? name : name.substring(0, dot);
}

String _trimStart(String s, String chars) {
  var i = 0;
  while (i < s.length && chars.contains(s[i])) {
    i++;
  }
  return s.substring(i);
}

String _trimEnd(String s, String chars) {
  var end = s.length;
  while (end > 0 && chars.contains(s[end - 1])) {
    end--;
  }
  return s.substring(0, end);
}

/// Text inside a C# interpolated string literal.
String _lit(String s) => s.replaceAll('\\', '\\\\').replaceAll('"', '\\"').replaceAll('{', '{{').replaceAll('}', '}}').replaceAll('\r', '\\r').replaceAll('\n', '\\n');
String _quote(String s) => '"${s.replaceAll('\\', '\\\\').replaceAll('"', '\\"').replaceAll('\r', '\\r').replaceAll('\n', '\\n').replaceAll('\t', '\\t')}"';
String _xml(String s) => s.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
